// 由 proto 脚本使用：把 classic-script 的 fabric.min.js / jszip.min.js
// 转成可被 esbuild 打包的 ES 模块（评估用，不进正式构建）。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');

export const FABRIC_SOURCE = fs.readFileSync(
  path.join(root, 'core', 'src', 'lib', 'fabric.min.js'),
  'utf8'
);
export const JSZIP_SOURCE = fs.readFileSync(
  path.join(root, 'core', 'src', 'lib', 'jszip.min.js'),
  'utf8'
);

// fabric.min.js 的 UMD 分派：
//   "undefined" != typeof exports ? exports.fabric = fabric : ...
// 文件内部又散落裸 fabric 标识符（如 fabric.util.object.extend(...)），
// 两者同时成立：既要用真实 module/exports 接住 UMD 分派，
// 也要把结果显式挂回 globalThis.fabric 供其余模块裸用。
export function wrapFabric(source) {
  return [
    '// AUTO-GENERATED by scripts/proto-esbuild-web.mjs — do not edit.',
    'const module = { exports: {} };',
    'const exports = module.exports;',
    '(function () {',
    source,
    '})();',
    'globalThis.fabric = exports.fabric;',
    "if (!globalThis.fabric) { throw new Error('fabric 未能注册到 globalThis'); }",
    'export default globalThis.fabric;',
    ''
  ].join('\n');
}

// jszip.min.js 是 Browserify 风格 UMD：
//   typeof exports === 'object' && typeof module !== 'undefined' ? module.exports = f()
// module.exports 本身就是 JSZip 类，不是 exports.JSZip。
export function wrapJSZip(source) {
  return [
    '// AUTO-GENERATED by scripts/proto-esbuild-web.mjs — do not edit.',
    'const module = { exports: {} };',
    'const exports = module.exports;',
    '(function () {',
    source,
    '})();',
    'globalThis.JSZip = module.exports;',
    "if (typeof globalThis.JSZip !== 'function') { throw new Error('JSZip 未能注册到 globalThis'); }",
    'export default globalThis.JSZip;',
    ''
  ].join('\n');
}
